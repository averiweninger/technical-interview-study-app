import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { signIn } from "./auth-fixture";

async function logout(page: import("@playwright/test").Page) {
  await page.getByRole("button", { name: "Account menu", exact: true }).click();
  await page.getByRole("button", { name: "Log out", exact: true }).click();
  await expect(page).toHaveURL(/\/login/);
}

test("new signup resumes incomplete setup and retries completion before returning to the requested page", async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const email = `onboarding-retry-${crypto.randomUUID()}@example.test`;
  await page.goto("/signup?next=/practice?topic=sql");
  await page.getByLabel("First name", { exact: true }).fill("Taylor");
  await page.getByLabel("Last name", { exact: true }).fill("Setup");
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("Synthetic-passphrase-123");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Check your email" })).toBeVisible();
  await page.goto(`/auth/callback?token_hash=${encodeURIComponent(`signup:${email}`)}&type=email&next=${encodeURIComponent("/practice?topic=sql")}`);
  await expect(page.getByRole("heading", { name: "Choose your career paths" })).toBeVisible();
  await page.getByRole("checkbox", { name: "Data Science", exact: true }).focus();
  await page.keyboard.press("Space");
  await page.getByLabel("Preferred career path").selectOption("data-science");
  await page.getByRole("button", { name: "Save paths and continue", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Review your preferences" })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Review your preferences" })).toBeVisible();
  await expect(page.getByRole("checkbox", { name: "Data Science", exact: true })).toBeChecked();
  await logout(page);
  // Sign-in must resume setup even if a different workspace route is requested.
  await page.goto("/login?next=/practice?topic=sql");
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("Synthetic-passphrase-123");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Review your preferences" })).toBeVisible();
  await page.getByLabel("Daily study goal (minutes)").fill("45");
  await page.getByLabel("Timezone", { exact: true }).fill("Pacific/Kiritimati");
  await page.getByRole("button", { name: "Complete setup", exact: true }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("could not be confirmed as saved");
  await expect(page.getByLabel("Daily study goal (minutes)")).toHaveValue("45");
  await page.getByRole("button", { name: "Complete setup", exact: true }).click();
  await expect(page).toHaveURL(/\/practice\?topic=sql$/);
  await page.goto("/settings");
  await expect(page.getByLabel("Preferred career path")).toHaveValue("data-science");
  await expect(page.getByLabel("Timezone", { exact: true })).toHaveValue("Pacific/Kiritimati");
  await expect(page.getByLabel("Interview date (optional)")).toHaveValue("");
  await logout(page);
  await signIn(page, email);
  await page.goto("/onboarding");
  const findings = await new AxeBuilder({ page }).analyze();
  expect(findings.violations.filter((entry) => entry.impact === "serious" || entry.impact === "critical")).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: testInfo.outputPath("onboarding-review.png"), fullPage: true });
});

test("multiple paths agree across editors and sessions; removal preserves progress and quiz history", async ({ page, request }, testInfo) => {
  test.setTimeout(120_000);
  const email = await signIn(page, `preference-persist-${crypto.randomUUID()}@example.test`);
  await page.goto("/lessons/python-variables");
  await page.getByRole("button", { name: "Start lesson", exact: true }).click();
  await page.getByRole("button", { name: "Mark lesson complete", exact: true }).click();
  await expect(page.getByRole("button", { name: "Lesson complete", exact: true })).toBeDisabled();
  await page.goto("/practice?topic=python");
  await page.getByRole("radio", { name: "B. String (str)" }).check();
  await page.getByRole("button", { name: "Check answer", exact: true }).click();
  await expect(page.getByText("Correct. Nicely reasoned.", { exact: true })).toBeVisible();
  await page.goto("/career-paths");
  await expect(page.getByRole("checkbox", { name: "Business Analytics", exact: true })).toBeChecked();
  await page.getByRole("checkbox", { name: "Software Engineering", exact: true }).check();
  await page.getByLabel("Preferred career path").selectOption("software-engineering");
  await page.getByRole("button", { name: "Save career paths", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Career paths saved" })).toBeVisible();
  await page.goto("/settings");
  await expect(page.getByRole("checkbox", { name: "Software Engineering", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "Business Analytics", exact: true })).toBeChecked();
  await page.getByRole("checkbox", { name: "Software Engineering", exact: true }).uncheck();
  await expect(page.getByLabel("Preferred career path")).toHaveValue("business-analytics");
  await page.getByRole("button", { name: "Save preferences", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Preferences saved" })).toBeVisible();
  await page.goto("/dashboard");
  await expect(page.getByText("Primary path:", { exact: false })).toContainText("Business Analytics");
  await expect(page.getByText("1 / 6", { exact: true })).toBeVisible();
  await expect(page.getByText("Practice score: 100%", { exact: true })).toBeVisible();
  await logout(page);
  await signIn(page);
  await page.goto("/career-paths");
  await expect(page.getByRole("checkbox", { name: "Software Engineering", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "Business Analytics", exact: true })).not.toBeChecked();
  await logout(page);
  await signIn(page, email);
  await page.goto("/career-paths");
  await expect(page.getByRole("checkbox", { name: "Business Analytics", exact: true })).toBeChecked();
  await expect(page.getByRole("checkbox", { name: "Software Engineering", exact: true })).not.toBeChecked();
  const findings = await new AxeBuilder({ page }).analyze();
  expect(findings.violations.filter((entry) => entry.impact === "serious" || entry.impact === "critical")).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: testInfo.outputPath("selected-career-paths.png"), fullPage: true });
  await page.getByRole("button", { name: "Save career paths", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "Career paths saved" })).toBeVisible();
  const identity = await request.post("http://127.0.0.1:54329/auth/v1/token?grant_type=password", { data: { email, password: "Synthetic-passphrase-123" } });
  const record = await identity.json() as { user: { user_metadata: Record<string, unknown> } };
  expect(record.user.user_metadata).toMatchObject({ selected_career_path_ids: ["business-analytics"], career_path_id: "business-analytics", first_name: "Taylor", unrelated_marker: "keep-fixture-metadata" });
});
